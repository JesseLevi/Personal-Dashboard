-- #163: seeds reference.ingredient_unit_masses from NEVO Portie-online
-- 2025/9.0 (26 CSVs, "maten -> grammen"), so recipe rows using eetlepel,
-- theelepel and stuk resolve to real grams instead of "?". Follow-up to
-- #161 (ADR-0013); the read path already exists and needs no changes --
-- lib/recipes/mass-resolution.ts's resolveMass and
-- lib/recipes/queries.ts's resolveIngredientUnitMass already implement
-- ADR-0011 §3's user-override -> reference -> unresolved precedence
-- against what was, until this migration, an empty table.
-- Implements ADR-0013 (docs/decisions/0013-nevo-nutrition-import.md,
-- amended for this ticket) and ADR-0011 §3; both are binding, this
-- migration only executes them.
--
-- Scope is Layer 1 only (measures -> grams). Density (deriving
-- milliliter/deciliter/liter/cup/fluid_ounce from volume) is explicitly
-- out of scope and is its own future ticket -- ADR-0011 §3's rule that the
-- two mechanisms never merge stands.
--
-- Row data is generated by scripts/import-nevo-portions.ts (mapping rules
-- documented at the top of that file) reading the git-ignored upstream
-- CSVs (NEVO2025_v9.0/Portie-online/*.csv, see .gitignore) and printing
-- the exact `insert into reference.ingredient_unit_masses (...) select
-- ...` statement pasted verbatim below. Re-running the script against a
-- future NEVO version regenerates this block; nothing here is hand-edited.
--
-- FK resolution is by NEVO-code (source_ref) via a join, never a
-- hardcoded UUID, so a (source_ref, unit) pair with no matching
-- reference.ingredients row simply inserts nothing -- the correct
-- behaviour for the small fraction of Portie codes not in the #161 seed,
-- not an error.
--
-- The leading DELETE makes this migration idempotent/re-runnable: running
-- it twice (or against a future NEVO version) replaces the prior NEVO-
-- sourced rows rather than duplicating or erroring on the
-- (ingredient_id, unit) unique constraint
-- (20260730000001_ingredient_library.sql). This table carries only
-- NEVO-portie-online rows today, so a full delete is safe; a future
-- second source into this table would need this narrowed to
-- `where source = 'NEVO-portie-online'`.

