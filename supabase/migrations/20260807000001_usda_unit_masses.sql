-- Row data is generated by scripts/import-usda-unit-masses.ts reading the
-- git-ignored upstream USDA CSVs (usda/fndds/..., usda/sr_legacy/..., see
-- .gitignore; downloaded from https://fdc.nal.usda.gov/download-datasets)
-- and printing the exact `insert into reference.ingredient_unit_masses
-- (...) select ... from (values ...) ...` statement pasted verbatim below.
-- Re-running the script against a freshly downloaded copy of the *same*
-- USDA vintage regenerates this block byte-for-byte; against a *different*
-- vintage it fails loudly (PortionMismatchError) instead of silently
-- reseeding different numbers under the same fdc_id -- see that script's
-- own header comment for the assertion mechanism.
--
-- Unlike #163's NEVO-portie-online seed (whose (NEVO code, unit) -> grams
-- mapping is derived algorithmically from NEVO's own household-measure
-- export), USDA's CSVs carry no NEVO linkage at all. Every row below is a
-- hand-curated pairing: a person read the actual reference.ingredients row
-- (name_nl/name_en, seeded by 20260806000001_nevo_nutrition_import.sql)
-- and the actual USDA food.csv description, and decided they denote the
-- same raw ingredient -- verified pairing-by-pairing, never by name-
-- similarity matching (a prior automated attempt at that scored 20-56%
-- precision, per the #164 ticket body). Every gram value is read directly
-- out of one specific food_portion.csv row (referenced by that row's own
-- primary key, not re-derived by pattern matching); scripts/import-usda-
-- unit-masses.ts's SOLID_PAIRINGS/LIQUID_PAIRINGS tables are the full
-- curation record and the source of truth -- the table below is a rendered
-- copy of the same data for reviewers who don't want to read TypeScript.
-- Every value was sanity-gated (g/cup in [25, 330], density in
-- [0.6, 1.5]); ingredients that failed to clear a real, exact USDA cup/
-- tbsp/tsp row were dropped rather than approximated -- see the script's
-- header for the specific staples/liquids rejected and why (wine, dry
-- pasta, split peas, molasses, etc.).
--
-- Prepared/canned follow-up (same ticket, #164/#157): the pairings above
-- only cover raw/dry staples, which left recipe lines written in cooked or
-- canned quantities (e.g. "2 cups Rijst witte gekookt", "1 cup Linzen
