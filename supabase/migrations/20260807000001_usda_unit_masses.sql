-- FoodData Central, extending #163's NEVO-portie-online seed (eetlepel/
-- theelepel/stuk) with two families that source doesn't cover:
--   - SOLID staples measured by `cup` (and `tablespoon`/`teaspoon` where
--     USDA has them): rice, flour, sugar, butter, oats, nuts, legumes,
--     cheese, spices, etc.
--   - LIQUIDS measured by `milliliter`, whose `grams` is that liquid's
--     density in g per 1 ml (milk, cream, oil, honey, syrup, vinegar, soy
--     sauce, broth, juice, water, yoghurt) -- the volume->ml bridge this
--     unlocks is lib/recipes/mass-resolution.ts's job (same PR), not this
--     migration's; this migration only seeds the raw density numbers.
-- Implements ADR-0011 §3/§5 (docs/decisions/0011-ingredient-library-and-
-- reference-data.md); that ADR is binding, this migration only executes it.
