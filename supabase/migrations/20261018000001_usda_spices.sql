-- #521: herbs and spices NEVO 2025/9.0 lacks (turmeric, fenugreek, ginger
-- ground, thyme, baking powder, vanilla extract, ...) added from USDA
-- FoodData Central SR Legacy 2018-04, plus the shared aliases that let recipe
-- import link them deterministically (ADR-0020 §3).
-- Implements ADR-0011 §4/§5 (one source per row, unknown = NULL never 0,
-- source/source_ref/source_version on every row) and ADR-0020 §2 (USDA rows
-- change only through migrations). NEVO rows are not touched; two NEVO rows
-- only gain an alias. Nothing is written to public.*.
--
-- ============================================================================
-- Provenance (ADR-0011 §5)
-- ============================================================================
-- The SQL below is generated by scripts/import-usda-spices.ts from the
-- git-ignored SR Legacy CSVs (usda/sr_legacy/..., https://fdc.nal.usda.gov/
-- download-datasets) and pasted verbatim. Every row is a hand-curated pair
-- (SPICES in that script is the curation record); the script re-reads the
-- CSVs and fails on any description or portion mismatch. source_ref is the
-- USDA fdc_id. kcal/protein/carbs/fat/fibre come from food_nutrient.csv
-- (nutrient ids 1008/1003/1005/1004/1079); a missing nutrient would be NULL.
-- theelepel/eetlepel masses come from real food_portion.csv rows (amount 1).
-- Attribution (ADR-0013 §2) stays per nutrient in the UI, not per source.
--
-- Alias keys are the output of normalizeIngredientName (lib/recipes/import/
-- normalize-name.ts), the same function the importer applies on lookup. It
-- strips "verse"/"gemalen", so "verse tijm" collapses to "tijm", which maps to
-- the dried row. The bare keys "gember" and "koriander" are deliberately not
-- claimed (they would capture "verse gember"/"verse koriander"), and neither is
-- "bakpoeder": baking powder is added by an admin as an eigen row.
--
